def save(name, art, pal, here):
    rows = [r.replace(' ', '.') for r in art.strip('\n').split('\n')]
    im = Image.new('RGBA', (16, 16))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row[:16]):
            im.putpixel((x, y), pal[ch])
    im.save(os.path.join(here, name + '.png'))


def main():
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'assets')
    os.makedirs(here, exist_ok=True)
    for i, art in enumerate(FIREFLY):
        save('firefly_%d' % i, art, PAL, here)
    for shell, (c, C) in SHELLS.items():
        pal = dict(PAL, c=c + (255,), C=C + (255,))
        for i, art in enumerate(BEETLE):
            save('%s_%d' % (shell, i), art, pal, here)
    save('flower', FLOWER, PAL, here)


if __name__ == '__main__':
    main()
